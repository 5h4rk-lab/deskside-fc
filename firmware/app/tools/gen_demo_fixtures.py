# PlatformIO pre script: embeds the two contract fixtures the demo build needs
# (news and teams, ../../contract/fixtures/*-normalised.json) as C++ raw string
# literals in src/demo/demo_fixtures.gen.h (git-ignored). One source of truth:
# the simulator reads the very same files at runtime. The header is rewritten
# only when its content changes, so an unchanged build does not recompile.
import os

Import("env")

project = env.subst("$PROJECT_DIR")
fixtures = os.path.normpath(os.path.join(project, "..", "..", "contract", "fixtures"))
out_path = os.path.join(project, "src", "demo", "demo_fixtures.gen.h")

parts = [
    "// Generated by tools/gen_demo_fixtures.py from contract/fixtures. Do not edit.\n",
    "#pragma once\n",
    "namespace demo_fixtures {\n",
]
for name, ident in (("news-normalised.json", "kNewsJson"), ("teams-normalised.json", "kTeamsJson")):
    with open(os.path.join(fixtures, name), encoding="utf-8") as f:
        text = f.read()
    delim = "FIXTURE"
    if (")" + delim + '"') in text:
        raise SystemExit("fixture %s contains the raw string terminator" % name)
    parts.append('constexpr const char* %s = R"%s(%s)%s";\n' % (ident, delim, text, delim))
parts.append("}  // namespace demo_fixtures\n")
content = "".join(parts)

old = None
if os.path.exists(out_path):
    with open(out_path, encoding="utf-8") as f:
        old = f.read()
if old != content:
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(content)
    print("gen_demo_fixtures: wrote", out_path)
