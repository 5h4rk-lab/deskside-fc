#!/usr/bin/env python3
"""Regenerates src/board/test_assets.h: a 96 x 96 PNG and JPEG for the image decoder test.

Run from firmware/app:   python3 tools/gen_test_assets.py
Needs Python 3 with Pillow (pip install pillow).

The picture is built so that a wrong channel order, swapped bytes, a wrong
stride or a mirrored image is obvious at a glance:
  top-left red, top-right green, bottom-left blue, bottom-right white,
  a black-to-white gradient bar across the middle,
  a black square in the top-left corner and a yellow one in the top-right corner.
The PNG is RGBA (what the helper serves for crests); the JPEG is baseline 4:4:4
(no chroma subsampling, so the colours stay sharp).
"""
import io
import os

from PIL import Image

SIZE = 96
HALF = SIZE // 2


def build():
    img = Image.new("RGBA", (SIZE, SIZE))
    px = img.load()
    for y in range(SIZE):
        for x in range(SIZE):
            if y < HALF:
                px[x, y] = (255, 0, 0, 255) if x < HALF else (0, 255, 0, 255)
            else:
                px[x, y] = (0, 0, 255, 255) if x < HALF else (255, 255, 255, 255)
    for y in range(40, 56):  # gradient bar
        for x in range(SIZE):
            v = round(x * 255 / (SIZE - 1))
            px[x, y] = (v, v, v, 255)
    for y in range(8):  # orientation markers
        for x in range(8):
            px[x, y] = (0, 0, 0, 255)
            px[SIZE - 1 - x, y] = (255, 255, 0, 255)
    return img


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return "inline constexpr unsigned char %s[] = {\n%s\n};\n" % (name, "\n".join(lines))


def main():
    img = build()
    png = io.BytesIO()
    img.save(png, "PNG", optimize=True)
    jpg = io.BytesIO()
    img.convert("RGB").save(jpg, "JPEG", quality=92, subsampling=0, progressive=False, optimize=False)
    out = os.path.join(os.path.dirname(__file__), "..", "src", "board", "test_assets.h")
    with open(out, "w") as f:
        f.write("// GENERATED by tools/gen_test_assets.py (python3 tools/gen_test_assets.py, needs Pillow). Do not edit.\n")
        f.write("// 96 x 96 test picture: red / green / blue / white quadrants, a black-to-white gradient bar,\n")
        f.write("// a black marker top-left and a yellow marker top-right.\n")
        f.write("#pragma once\n\nnamespace test_assets {\n\n")
        f.write("constexpr int kSize = %d;\n\n" % SIZE)
        f.write(c_array("kPng", png.getvalue()) + "\n")
        f.write(c_array("kJpeg", jpg.getvalue()) + "\n")
        f.write("}  // namespace test_assets\n")
    print("png %d bytes, jpeg %d bytes" % (len(png.getvalue()), len(jpg.getvalue())))


main()
